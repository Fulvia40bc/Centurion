#!/usr/bin/env python3
"""Write docs/strings.txt: the printable strings of the game's data object with their linear addresses.

Usage: strings_dump.py disasm/le/obj2.bin docs/strings.txt   (obj2.bin from tools/disasm.ps1)
"""
import re, sys

BASE = 0xB0000
END = 0x11AF7C - BASE + 200   # just past the highest data address the game code refers to (fixups)

def main():
    d = open(sys.argv[1], 'rb').read()[:END]
    out = ['# Strings of the game data object (AC_MAIN.EXE object 2): linear address (base 0xB0000) and text.',
           '# Printable runs of 4+ chars with 3+ letters; a newline in a text is written as \\n, a CR as \\r.',
           '# Library strings (Miles AIL, Watcom runtime, Fastgraph) follow the game strings from about 0xB9000: skip them.',
           '# Generated by tools/strings_dump.py.']
    for m in re.finditer(rb'[\x20-\x7e\t\r\n]{4,}', d):
        t = m.group().decode('latin1')
        if sum(c.isalpha() for c in t) < 3:
            continue
        t = t.replace('\r', '\\r').replace('\n', '\\n').replace('\t', '\\t')
        out.append('%08X %s' % (BASE + m.start(), t))
    with open(sys.argv[2], 'w', encoding='ascii', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print(len(out) - 4, 'strings')

if __name__ == '__main__':
    main()
